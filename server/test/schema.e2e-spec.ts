import { DataSource } from 'typeorm';
import { MIGRATIONS } from '../src/migrations';
import { createTempDb, dataSourceFor } from './db';

const LAYER1_TABLES = ['attachments', 'audit_log', 'changes', 'docs', 'records', 'roles', 'schema_meta', 'sessions', 'user_permissions', 'users',
  // المرحلة 5 (migration 0007) — فاضية: مفيش بيانات بتتزرع
  'approval_decisions', 'approval_document_types', 'approval_level_approvers', 'approval_request_steps', 'approval_requests', 'approval_state_log', 'approval_workflow_levels', 'approval_workflows',
  'document_counters', 'document_numbers', 'idempotency_keys', 'notifications', 'projects', 'user_action_permissions',
  // المرحلة 6.1 — فاضية: الترحيل بموافقة منفصلة
  'customer_contacts', 'customers', 'suppliers', 'module_cutover'].sort();

async function tables(ds: DataSource): Promise<string[]> {
  const rows: { table_name: string }[] = await ds.query(
    `SELECT table_name FROM information_schema.tables WHERE table_schema = 'public' AND table_type = 'BASE TABLE' AND table_name <> 'typeorm_migrations' ORDER BY 1`,
  );
  return rows.map((r) => r.table_name);
}

describe('migrations (layer 1) on a fresh PostgreSQL', () => {
  let db: { url: string; drop: () => Promise<void> };
  let ds: DataSource;

  beforeAll(async () => {
    db = await createTempDb();
    ds = await dataSourceFor(db.url).initialize();
  });
  afterAll(async () => {
    await ds?.destroy();
    await db?.drop();
  });

  it('runs all migrations from zero', async () => {
    expect(await tables(ds)).toEqual([]);
    const ran = await ds.runMigrations({ transaction: 'each' });
    expect(ran.map((m) => m.name)).toEqual(MIGRATIONS.map((m) => m.name));
    expect(await tables(ds)).toEqual(LAYER1_TABLES);
    expect(await ds.showMigrations()).toBe(false); // مفيش pending
  });

  it('entities match the migrated schema exactly (no drift, synchronize would do nothing)', async () => {
    const sql = await ds.driver.createSchemaBuilder().log();
    expect(sql.upQueries.map((q) => q.query)).toEqual([]);
  });

  it('seeds schema_meta', async () => {
    const rows = await ds.query(`SELECT key, value FROM schema_meta ORDER BY key`);
    expect(rows).toEqual([
      { key: 'data_layer', value: 'records-v1' },
      { key: 'legacy_schema_version', value: 9 },
    ]);
  });

  describe('constraints', () => {
    const insertUser = (u: string, algo = 'argon2id', salt: string | null = null) =>
      ds.query(`INSERT INTO users (username, password_algo, password_hash, password_salt) VALUES ($1, $2, 'h', $3) RETURNING id`, [u, algo, salt]);

    it('username is unique case-insensitively', async () => {
      await insertUser('Ahmed');
      await expect(insertUser('ahmed')).rejects.toThrow(/uq_users_username_lower/);
    });
    it('scrypt users must keep their salt; unknown algo rejected; blank username rejected', async () => {
      await expect(insertUser('legacy1', 'scrypt', null)).rejects.toThrow(/ck_users_scrypt_salt/);
      await expect(insertUser('legacy2', 'scrypt', 'abc')).resolves.toBeDefined();
      await expect(insertUser('x1', 'bcrypt')).rejects.toThrow(/ck_users_password_algo/);
      await expect(insertUser('   ')).rejects.toThrow(/ck_users_username_not_blank/);
    });
    it('uuid ids are generated by gen_random_uuid()', async () => {
      const [{ id }] = await insertUser('uuid-check');
      expect(id).toMatch(/^[0-9a-f-]{36}$/);
    });
    it('records: composite PK (collection,id), rev > 0, jsonb data', async () => {
      await ds.query(`INSERT INTO records (collection, id, data, project_id) VALUES ('employees', 'e1', '{"name":"محمد","salary":5000}', 'p1')`);
      await ds.query(`INSERT INTO records (collection, id, data) VALUES ('workers', 'e1', '{}')`); // نفس id في collection تانية = مسموح
      await expect(ds.query(`INSERT INTO records (collection, id, data) VALUES ('employees', 'e1', '{}')`)).rejects.toThrow(/duplicate key/);
      await expect(ds.query(`INSERT INTO records (collection, id, data, rev) VALUES ('employees', 'e2', '{}', 0)`)).rejects.toThrow(/ck_records_rev_positive/);
      const [r] = await ds.query(`SELECT data->>'name' AS name, (data->>'salary')::int AS salary, rev FROM records WHERE collection='employees' AND id='e1'`);
      expect(r).toEqual({ name: 'محمد', salary: 5000, rev: 1 });
    });
    it('changes.op restricted, seq increases', async () => {
      await expect(ds.query(`INSERT INTO changes (collection, record_id, op, rev) VALUES ('employees','e1','upsert',1)`)).rejects.toThrow(/ck_changes_op/);
      const a = await ds.query(`INSERT INTO changes (collection, record_id, op, rev) VALUES ('employees','e1','insert',1) RETURNING seq`);
      const b = await ds.query(`INSERT INTO changes (collection, record_id, op, rev) VALUES ('employees','e1','update',2) RETURNING seq`);
      expect(BigInt(b[0].seq)).toBeGreaterThan(BigInt(a[0].seq));
    });
    it('deleting a user cascades to sessions and user_permissions', async () => {
      const [{ id }] = await insertUser('cascade-me');
      await ds.query(`INSERT INTO sessions (user_id, token_hash, expires_at) VALUES ($1, 'th1', now() + interval '1 day')`, [id]);
      await ds.query(`INSERT INTO user_permissions (user_id, page, can_view) VALUES ($1, 'employees', true)`, [id]);
      await ds.query(`DELETE FROM users WHERE id = $1`, [id]);
      expect((await ds.query(`SELECT count(*)::int AS n FROM sessions WHERE user_id = $1`, [id]))[0].n).toBe(0);
      expect((await ds.query(`SELECT count(*)::int AS n FROM user_permissions WHERE user_id = $1`, [id]))[0].n).toBe(0);
    });
    it('partial index for live records exists', async () => {
      const [ix] = await ds.query(`SELECT indexdef FROM pg_indexes WHERE indexname = 'ix_records_collection_live'`);
      expect(ix.indexdef).toMatch(/WHERE \(deleted_at IS NULL\)/);
    });
  });

  it('reverts every migration back to an empty schema, then re-applies cleanly', async () => {
    for (let i = 0; i < MIGRATIONS.length; i++) await ds.undoLastMigration({ transaction: 'each' });
    expect(await tables(ds)).toEqual([]);
    await ds.runMigrations({ transaction: 'each' });
    expect(await tables(ds)).toEqual(LAYER1_TABLES);
  });
});
