const { openApp } = require('./harness');
const { ok, eq, summary, baseUser } = require('./lib');
(async () => {
  const seed = { users: [baseUser], schemaVersion: 9, projects: [{ id: 'pA', code: 'P1', name: 'م', customerId: 'cA', status: 'الدراسة والتخطيط' }],
    clients: { customers: [{ id: 'cA', name: 'ع', code: 'C', projects: [], contracts: [], invoices: [], boqs: [], workSurveys: [], collections: [] }] } };
  const { browser, page, errors } = await openApp(seed);
  const ev = (f, a) => page.evaluate(f, a);
  console.log('[1] logic: skip counts as progress; stage skip');
  eq(await ev(() => { const p = DATA.projects[0]; return pwSkipStage(p, 'study', '').ok; }), false, 'stage skip needs reason');
  eq(await ev(() => { const p = DATA.projects[0]; return pwSkipStage(p, 'tender', 'x').ok; }), false, 'exclusive stage cannot be skipped');
  eq(await ev(() => { const p = DATA.projects[0]; return pwSkipStage(p, 'study', 'مش مطلوبة').ok; }), true, 'stage skipped');
  eq(await ev(() => { const p = DATA.projects[0]; return pwStageStatus(p, pwWorkflowOf(p)[0]); }), 'skipped', 'all-skipped stage = skipped');
  eq(await ev(() => pwCurrent(DATA.projects[0]).stageKey), 'docs', 'moved to next stage');
  ok(await ev(() => pwProgress(DATA.projects[0])) >= 8, 'skipped steps count as progress');
  console.log('[2] UI: skip reason only on skip');
  await ev(() => { goToPage('projects'); projectFilters.detailId = 'pA'; rerenderCurrentPage(); });
  await page.waitForTimeout(300);
  await ev(() => { const p = DATA.projects[0]; openStepModal(p, pwCurrent(p).stepKey); });
  await page.waitForTimeout(500);
  ok(await ev(() => document.getElementById('pwReasonWrap').style.display === 'none'), 'reason hidden initially');
  await ev(() => document.getElementById('pwSkip').click());
  ok(await ev(() => document.getElementById('pwReasonWrap').style.display !== 'none'), 'reason shown after skip click');
  eq(await ev(() => document.querySelector('.cl-att-item') ? 1 : 0), 0, 'no attachments yet');
  await ev(() => closeModal()); await page.waitForTimeout(500);
  await ev(() => { const b = document.querySelector('.ppt2-step [data-act="skip"]'); b.click(); });
  await page.waitForTimeout(500);
  ok(await ev(() => !!document.getElementById('pwReasonOnly')), 'card skip opens reason modal');
  await ev(() => { document.getElementById('pwReasonOnly').value = 'سبب'; document.getElementById('pwReasonOk').click(); });
  await page.waitForTimeout(400);
  eq(await ev(() => Object.values(DATA.projects[0].stepMeta).filter(m => m.status === 'skipped' && m.skipReason === 'سبب').length), 1, 'step skipped with reason');
  console.log('[3] modal order & visuals');
  await ev(() => { const p = DATA.projects[0]; pwAddFiles(p, pwCurrent(p).stepKey, [{ id: 'f1', name: 'عقد.pdf' }]); openStepModal(p, pwCurrent(p).stepKey); });
  await page.waitForTimeout(500);
  const order = await ev(() => { const h = document.getElementById('appModal').innerHTML; return [h.indexOf('pwCmText'), h.indexOf('pwAttList'), h.indexOf('pw-hist')]; });
  ok(order[0] > 0 && order[0] < order[1] && order[1] < order[2], 'note above attachments above history: ' + order);
  ok(await ev(() => !!document.querySelector('.cl-att-ico') && !!document.querySelector('.pw-hist-item')), 'nice attachments + history');
  const geo = await ev(() => { const r = document; return 1; });
  eq(errors.length, 0, 'no page errors: ' + errors.join('|'));
  await browser.close(); summary();
})();
