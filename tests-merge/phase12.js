const { openApp } = require('./harness');
const { ok, eq, summary, baseUser } = require('./lib');
(async () => {
  const seed = { users: [baseUser], schemaVersion: 7, projects: [], auditLog: [], clients: { customers: [{ id: 'cA', name: 'أمل', code: 'C1', projects: [], boqs: [], workSurveys: [], collections: [], guarantees: [], invoices: [{ no: 'INV-1', value: 10 }], contracts: [{ id: 'CT-1', title: 'ع', value: 100 }] }] } };
  const { browser, page, errors } = await openApp(seed);
  const w = (ms = 300) => page.waitForTimeout(ms);
  const yes = async () => { await page.waitForSelector('#appConfirmModal'); await page.click('#appConfirmModal button[data-c="1"]'); await w(500); };
  console.log('[1] role templates');
  const t = await page.evaluate(() => { const T = roleTemplates(); const s = T.clientsSales.pages, a = T.clientsAccounts.pages; return [s['clients.contracts'], s['clients.invoices'], a['clients.invoices'], a['clients.contracts'], s['clients.contracts'].delete]; });
  eq(t[0], { view: true, add: true, edit: true, delete: false }, 'sales: contracts add/edit, no delete');
  eq(t[1], { view: true, add: false, edit: false, delete: false }, 'sales: invoices view only');
  eq(t[2].add, true, 'accounts: invoices add'); eq(t[3].add, false, 'accounts: contracts read-only');
  ok(await page.evaluate(() => Object.keys(roleTemplates().clientsProjects.pages).includes('clients.comparison')), 'new pages present in templates');
  console.log('[2] enforcement as clientsSales (non-admin)');
  await page.evaluate(() => { window.__realPerms = getUserPerms; window.getUserPerms = () => roleTemplates().clientsSales; });
  await page.evaluate(() => openClientInvoiceModal()); await w(200);
  ok(await page.evaluate(() => !document.querySelector('#btnSaveClInv')), 'add invoice blocked');
  await page.evaluate(() => openContractModal()); await w(300);
  ok(await page.evaluate(() => !!document.querySelector('#btnSaveContract')), 'add contract allowed'); await page.evaluate(() => closeModal());
  await page.evaluate(() => { contractFilters.detailKey = ''; goToPage('clients.contracts'); }); await w();
  await page.click('.btn-del-ct'); await w(400);
  ok(await page.evaluate(() => !document.querySelector('#appConfirmModal')), 'delete contract blocked (no confirm dialog)');
  eq(await page.evaluate(() => clCustomerById('cA').contracts.length), 1, 'contract still there');
  console.log('[3] enforcement as admin + auto audit');
  await page.evaluate(() => { window.getUserPerms = window.__realPerms; });
  await page.evaluate(() => clAuditBaseline());
  await page.evaluate(() => { const c = clCustomerById('cA'); c.contracts.push({ id: 'CT-2', title: 'ثاني', value: 5 }); clUpsertCustomer(c); });
  await page.evaluate(() => { const c = clCustomerById('cA'); c.contracts[0].value = 999; clUpsertCustomer(c); });
  await page.evaluate(() => { const c = clCustomerById('cA'); c.invoices = []; clUpsertCustomer(c); });
  const log = await page.evaluate(() => DATA.auditLog.map(a => a.action + '|' + a.details.split(' — ')[0]));
  ok(['إضافة عقد|CT-2', 'تعديل عقد|CT-1', 'حذف مستخلص|INV-1'].every(x => log.includes(x)), 'audit rows for add/edit/delete', log);
  await page.evaluate(() => { goToPage('clients.contracts'); }); await w();
  await page.click('.btn-del-ct'); await yes();
  eq(await page.evaluate(() => clCustomerById('cA').contracts.length), 1, 'admin delete works');
  const n = await page.evaluate(() => DATA.auditLog.filter(a => a.action === 'حذف عقد').length);
  eq(n, 1, 'delete logged exactly once');
  await page.evaluate(() => { const c = clCustomerById('cA'); c.guarantees = [{ id: 'G1', amount: 1 }]; });
  summary(errors); await browser.close();
})();
